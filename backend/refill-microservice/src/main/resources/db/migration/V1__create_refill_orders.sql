-- Baseline schema: the tables as Hibernate previously generated them.
-- IF NOT EXISTS makes this a no-op on databases that already have them (all four
-- services share one database, so Flyway baselines each service at version 0
-- and then runs this script).

CREATE TABLE IF NOT EXISTS refill_orders
(
    refill_order_id VARCHAR(255) NOT NULL PRIMARY KEY,
    member_id       VARCHAR(255) NOT NULL,
    order_date      TIMESTAMP(6) NOT NULL,
    member_location VARCHAR(255) NOT NULL,
    order_status    VARCHAR(50)  NOT NULL
        CHECK (order_status IN ('PENDING', 'CONFIRMED', 'IN_PROGRESS', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    order_type      VARCHAR(50)  NOT NULL CHECK (order_type IN ('SCHEDULED', 'ADHOC')),
    subscription_id VARCHAR(255),
    delivery_date   TIMESTAMP(6),
    tracking_number VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS refill_order_line_items
(
    line_item_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drug_code       VARCHAR(255)   NOT NULL,
    drug_name       VARCHAR(255)   NOT NULL,
    quantity        INTEGER        NOT NULL CHECK (quantity >= 1),
    prescription_id VARCHAR(255),
    unit_price      NUMERIC(10, 2) NOT NULL,
    total_price     NUMERIC(10, 2),
    refill_order_id VARCHAR(255) REFERENCES refill_orders (refill_order_id)
);
